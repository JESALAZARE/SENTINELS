/* ── Sentinels · PML Cloudflare Worker ───────────────────────────────
   The only door to the portal's market data: the stored files the robots
   keep in the private R2 bucket (prices, long-term history, NodoP catalog,
   exchange rate, SEN demand) and on-demand queries to CENACE's price web
   services for ANY NodoP (SW-PML) or load zone / distributed node (SW-PEND)
   of the catalog (the browser can't call them: no CORS headers, port 8082).
   - every route but /health needs the client's market pass
     (Authorization: Bearer <clientId>.<HMAC(DATA_SECRET, "market:<clientId>")>,
     issued by the admin panel into the client's encrypted vault); the client's
     vault must exist on the site and not be inactive;
   - each client has an hourly and daily request budget, so one pass can't
     download everything;
   - accepts only GET requests from the site's origins (ALLOWED_ORIGINS);
   - validates the query and caps it at 31 days and 20 NodosP / 10 load zones;
   - splits it into the 7-day windows CENACE allows and fetches them in parallel;
   - caches every window in Cloudflare's cache (published days for a week,
     days that may still change for 30 minutes), so CENACE sees few calls;
   - returns numbers, always in the row shape of the stored pml/<sistema>/<nodo>.json files
     ({ fecha, hora, pml, pml_ene, pml_per, pml_cng }; for load zones the PEND
     "pz" fields are mapped to the same names).

     GET /pml?sistema=SIN&proceso=MDA&nodos=06CDU-400&desde=2026-10-01&hasta=2026-10-26
     GET /pend?sistema=BCS&proceso=MDA&zonas=LOS CABOS,LA PAZ&desde=2026-10-01&hasta=2026-10-26
     GET /demanda?gerencia=10 (today's hourly demand, generation and forecast of a system or
                               region, from CENACE's "Operación del SEN" page; cached 1 minute,
                               &fresh=1 accepts at most 15 seconds;
                               previa = hour 24 of the previous day when CENACE sends it)
     GET /datos/<path>.json   (a stored file of the R2 bucket: pml/…, resumen/…, nodos/…, fx/…, demanda/…)
     GET /ofertas/<path>.json (MEM Insights: a summary of the private offers bucket, resumen/<path>.json.gz,
                               written by scripts/ofertas-resumen.mjs; only summaries, never the raw offers)
     GET /health              (public; ?cenace=1 also checks that CENACE answers)
     GET /admin/check         (Authorization: Bearer <DATA_SECRET>; setup check for the admin panel)

   Configure in Cloudflare (Settings → Variables and Secrets / Bindings):
     ALLOWED_ORIGINS  text   — https://sentinels.com.mx
     SITE_URL         text   — https://sentinels.com.mx (where the client vaults are published)
     DATA_SECRET      secret — generated by the admin panel ("Datos de mercado")
     DATOS            R2 bucket binding — the private bucket the robots write to
     OFERTAS          R2 bucket binding — sentinels-ofertas, the private offers bucket (MEM Insights)
   Plain fetch() so the file can be pasted into the Cloudflare dashboard editor (no build step).
   Setup steps: pml-worker/LEEME.md */

const MAX_DAYS = 31;
// Request budget per client, counted per Cloudflare location (approximate, but enough to stop
// bulk downloads with one pass). History files have their own, smaller daily budget.
// An "Excel + hourly" of the whole history is ~170 requests; the SEN demand widget makes 30 an hour.
const LIMITS = { hour: 400, day: 2000, historyDay: 150 };
const DATA_PATH = /^(pml|resumen|nodos|fx|demanda)\/[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)*\.json$/;
// MEM Insights summaries: /ofertas/<curva|desvio|costos|hidro|participacion|reservas|ajuste>/….json
const OFFERS_PATH = /^(curva|desvio|costos|hidro|participacion|reservas|ajuste)\/[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)*\.json$/;
// SW-PML: NodosP by key (06CDU-400). SW-PEND: load zones by name; spaces go as "-" in the URL.
const SERVICES = {
  pml: { url: 'https://ws01.cenace.gob.mx:8082/SWPML/SIM', label: 'SW-PML', param: 'nodos', max: 20, key: 'clv_nodo', what: 'NodoP keys',
    fields: ['pml', 'pml_ene', 'pml_per', 'pml_cng'],
    clean: s => s.trim().toUpperCase(), valid: s => /^[0-9A-Z][0-9A-Z.-]{1,19}$/.test(s), toPath: s => s },
  pend: { url: 'https://ws01.cenace.gob.mx:8082/SWPEND/SIM', label: 'SW-PEND', param: 'zonas', max: 10, key: 'zona_carga', what: 'load zone names',
    fields: ['pz', 'pz_ene', 'pz_per', 'pz_cng'],
    clean: s => s.trim().toUpperCase().replace(/-/g, ' ').replace(/\s+/g, ' '), valid: s => /^[0-9A-Z][0-9A-Z. ]{1,39}$/.test(s), toPath: s => s.replace(/ /g, '-') }
};
// First operating day with published prices (SW-PML technical manual)
const FIRST = { MDA: { SIN: '2016-01-29', BCA: '2016-01-27', BCS: '2016-03-23' }, MTR: { SIN: '2017-01-27', BCA: '2017-01-27', BCS: '2017-01-27' } };

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const origin = request.headers.get('Origin') || '';
    const allowed = (env.ALLOWED_ORIGINS || 'https://sentinels.com.mx').split(',').map(s => s.trim()).filter(Boolean);
    const cors = {
      'Access-Control-Allow-Origin': allowed.includes(origin) ? origin : allowed[0],
      'Vary': 'Origin',
      'Access-Control-Allow-Methods': 'GET, OPTIONS',
      'Access-Control-Allow-Headers': 'Authorization',
      'Access-Control-Max-Age': '86400'
    };
    if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers: cors });
    const json = (obj, status = 200, cache = 'no-store') =>
      new Response(JSON.stringify(obj), { status, headers: { ...cors, 'Content-Type': 'application/json', 'Cache-Control': cache } });

    try {
      if (url.pathname === '/health') {
        if (!url.searchParams.has('cenace')) return json({ ok: true, service: 'sentinels-pml', configured: !!(env.DATA_SECRET && env.DATOS) });
        // Setup check: can this Worker reach SW-PML (port 8082)? One cached day of one NodoP.
        const y = addDays(todayMX(), -1), t0 = Date.now();
        try {
          const r = await fetchWindow(SERVICES.pml, { sistema: 'SIN', proceso: 'MDA', items: ['06CDU-400'] }, y, y, ctx);
          const hours = (r[0] && r[0].Valores || []).length;
          return json({ ok: hours > 0, service: 'sentinels-pml', cenace: hours > 0 ? 'reachable' : 'no data', day: y, hours, ms: Date.now() - t0 });
        } catch (e) {
          return json({ ok: false, service: 'sentinels-pml', cenace: 'unreachable', error: String(e.message || e) }, 502);
        }
      }
      if (!allowed.includes(origin)) return json({ error: 'forbidden', message: 'Origin not allowed.' }, 403);
      if (request.method !== 'GET') return json({ error: 'not_found' }, 404);
      if (!env.DATA_SECRET || !env.DATOS) return json({ error: 'not_configured', message: 'Market data is not configured yet.' }, 503);

      if (url.pathname === '/admin/check') {
        if (!safeEqual(request.headers.get('Authorization') || '', 'Bearer ' + env.DATA_SECRET)) return json({ error: 'unauthorized' }, 401);
        const [catalogo, estado] = await Promise.all([env.DATOS.head('nodos/catalogo.json'), env.DATOS.head('resumen/estado.json')]);
        return json({ ok: true, catalogo: !!catalogo, historico: !!estado, actualizado: estado ? estado.uploaded : null });
      }

      const id = await authClient(request, env);
      const history = url.pathname.startsWith('/datos/resumen/') && url.pathname !== '/datos/resumen/index.json';
      await spend(id, history, ctx);

      if (url.pathname.startsWith('/datos/')) {
        const key = url.pathname.slice(7);
        if (!DATA_PATH.test(key)) return json({ error: 'not_found' }, 404);
        const obj = await env.DATOS.get(key);
        if (!obj) return json({ error: 'not_found' }, 404);
        // Only the signed-in browser may keep a copy; never a shared cache
        return new Response(obj.body, { headers: { ...cors, 'Content-Type': 'application/json', 'Cache-Control': 'private, max-age=300', 'ETag': obj.httpEtag } });
      }
      if (url.pathname.startsWith('/ofertas/')) {
        const key = url.pathname.slice(9);
        if (!OFFERS_PATH.test(key)) return json({ error: 'not_found' }, 404);
        if (!env.OFERTAS) return json({ error: 'not_configured', message: 'MEM Insights is not configured yet.' }, 503);
        // The robot stores the summaries gzipped; the browser receives plain JSON
        const obj = await env.OFERTAS.get(`resumen/${key}.gz`);
        if (!obj) return json({ error: 'not_found' }, 404);
        return new Response(obj.body.pipeThrough(new DecompressionStream('gzip')),
          { headers: { ...cors, 'Content-Type': 'application/json', 'Cache-Control': 'private, max-age=600', 'ETag': obj.httpEtag } });
      }
      if (url.pathname === '/demanda') return json(await demanda(url.searchParams, ctx), 200, 'no-store');
      const svc = Object.hasOwn(SERVICES, url.pathname.slice(1)) ? SERVICES[url.pathname.slice(1)] : null;
      if (!svc) return json({ error: 'not_found' }, 404);

      const q = parse(url.searchParams, svc);
      const windows = [];
      for (let ini = q.desde; ini <= q.hasta; ini = addDays(ini, 7)) windows.push([ini, minDate(addDays(ini, 6), q.hasta)]);
      const parts = await Promise.all(windows.map(([a, b]) => fetchWindow(svc, q, a, b, ctx)));

      const out = Object.fromEntries(q.items.map(n => [n, []])), row = rowOf(svc);
      for (const res of parts) for (const r of res) {
        const k = svc.clean(String(r[svc.key] || ''));
        if (out[k]) out[k].push(...(r.Valores || []).map(row));
      }
      for (const n of q.items) out[n].sort((a, b) => a.fecha === b.fecha ? a.hora - b.hora : a.fecha < b.fecha ? -1 : 1);
      // The signed-in browser may reuse the answer briefly; Cloudflare's cache holds the CENACE windows
      return json({ sistema: q.sistema, proceso: q.proceso, desde: q.desde, hasta: q.hasta, unidades: '$/MWh', fuente: 'CENACE ' + svc.label, [svc.param]: out }, 200, 'private, max-age=300');
    } catch (e) {
      if (e.status) return json({ error: e.code || 'error', message: e.message }, e.status);
      console.error(e);
      return json({ error: 'upstream', message: 'CENACE did not answer. Please try again later.' }, 502);
    }
  }
};

/* ── Market pass and request budget ────────────── */
function fail(status, code, message) { return Object.assign(new Error(message), { status, code }); }
function safeEqual(a, b) {
  if (typeof a !== 'string' || typeof b !== 'string' || a.length !== b.length) return false;
  let d = 0;
  for (let i = 0; i < a.length; i++) d |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return d === 0;
}
async function hmacHex(secret, msg) {
  const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  const sig = new Uint8Array(await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(msg)));
  return Array.from(sig, b => b.toString(16).padStart(2, '0')).join('');
}

// The pass is HMAC(DATA_SECRET, "market:<id>"); the client must still exist and be active on the site
async function authClient(request, env) {
  const m = /^Bearer ([0-9a-f]{32})\.([0-9a-f]{64})$/.exec(request.headers.get('Authorization') || '');
  if (!m) throw fail(401, 'unauthorized', 'Please sign in to see market data.');
  const [, id, token] = m;
  if (!safeEqual(await hmacHex(env.DATA_SECRET, 'market:' + id), token)) throw fail(401, 'unauthorized', 'Your market data access is not valid. Please sign in again.');
  const site = (env.SITE_URL || 'https://sentinels.com.mx').replace(/\/$/, '');
  const r = await fetch(`${site}/client-portal/data/clients/${id}.json`, { cf: { cacheTtl: 60, cacheEverything: true } });
  if (r.status === 404) throw fail(403, 'no_account', 'This account no longer exists.');
  if (!r.ok) throw fail(503, 'unavailable', 'Market data is temporarily unavailable.');
  if ((await r.json()).status === 'inactive') throw fail(403, 'inactive', 'Your portal access is paused. Please contact support.');
  return id;
}

// Counters live in this location's cache (and in memory while the isolate lives), so they
// are approximate: enough to stop one pass from downloading the whole history.
const COUNTS = new Map();
async function spend(id, history, ctx) {
  const now = new Date().toISOString(), cache = typeof caches !== 'undefined' ? caches.default : null;
  const buckets = [['h', now.slice(0, 13), LIMITS.hour, 3700], ['d', now.slice(0, 10), LIMITS.day, 90000]];
  if (history) buckets.push(['r', now.slice(0, 10), LIMITS.historyDay, 90000]);
  const seen = await Promise.all(buckets.map(async ([kind, period]) => {
    const name = `${id}/${kind}/${period}`;
    let n = COUNTS.get(name) || 0;
    if (cache) { const hit = await cache.match(new Request(`https://sentinels-pml.cache/budget/${name}`)); if (hit) n = Math.max(n, Number(await hit.text()) || 0); }
    return n;
  }));
  if (buckets.some(([, , max], i) => seen[i] >= max)) {
    console.log(JSON.stringify({ limit: id, history }));
    throw fail(429, 'too_many', 'You have reached the market data limit for now. Please try again later.');
  }
  if (COUNTS.size > 5000) COUNTS.clear();
  buckets.forEach(([kind, period, , ttl], i) => {
    const name = `${id}/${kind}/${period}`;
    COUNTS.set(name, seen[i] + 1);
    if (cache) ctx.waitUntil(cache.put(new Request(`https://sentinels-pml.cache/budget/${name}`), new Response(String(seen[i] + 1), { headers: { 'Cache-Control': `public, max-age=${ttl}` } })));
  });
}

/* ── Query ─────────────────────────────────────── */
const ISO = /^\d{4}-\d{2}-\d{2}$/;
const addDays = (f, n) => new Date(Date.parse(f + 'T00:00:00Z') + n * 864e5).toISOString().slice(0, 10);
const minDate = (a, b) => a < b ? a : b;
const todayMX = () => new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Mexico_City' }).format(new Date());

function parse(p, svc) {
  const sistema = p.get('sistema'), proceso = p.get('proceso');
  if (!['SIN', 'BCA', 'BCS'].includes(sistema)) throw fail(400, 'bad_request', 'sistema must be SIN, BCA or BCS.');
  if (!['MDA', 'MTR'].includes(proceso)) throw fail(400, 'bad_request', 'proceso must be MDA or MTR.');
  const items = [...new Set(String(p.get(svc.param) || '').split(',').map(svc.clean).filter(Boolean))];
  if (!items.length || items.length > svc.max || !items.every(svc.valid)) {
    throw fail(400, 'bad_request', `${svc.param} must list 1 to ${svc.max} ${svc.what}.`);
  }
  let desde = p.get('desde'), hasta = p.get('hasta');
  if (!ISO.test(desde || '') || !ISO.test(hasta || '') || desde > hasta) throw fail(400, 'bad_request', 'desde and hasta must be dates (YYYY-MM-DD), desde ≤ hasta.');
  // Published range: MDA up to tomorrow, MTR up to 7 days ago
  const last = proceso === 'MDA' ? addDays(todayMX(), 1) : addDays(todayMX(), -7);
  desde = desde < FIRST[proceso][sistema] ? FIRST[proceso][sistema] : desde;
  hasta = minDate(hasta, last);
  if (desde > hasta) throw fail(422, 'not_published', `${proceso} prices are not published for those dates.`);
  if ((Date.parse(hasta) - Date.parse(desde)) / 864e5 + 1 > MAX_DAYS) throw fail(400, 'too_long', `Query at most ${MAX_DAYS} days at a time.`);
  return { sistema, proceso, items: items.sort(), desde, hasta };
}

/* ── CENACE windows (cached) ───────────────────── */
async function fetchWindow(svc, q, a, b, ctx) {
  const path = `${q.sistema}/${q.proceso}/${q.items.map(svc.toPath).join(',')}/${a.replace(/-/g, '/')}/${b.replace(/-/g, '/')}/JSON`;
  const cache = typeof caches !== 'undefined' ? caches.default : null;
  const key = new Request(`https://sentinels-pml.cache/${svc.param}/${path}`);
  if (cache) { const hit = await cache.match(key); if (hit) return hit.json(); }

  const res = await fetch(`${svc.url}/${path}`, { headers: { Accept: 'application/json' }, cf: { cacheTtl: 0 } });
  if (res.status === 204 || res.status === 404) return [];
  if (!res.ok) throw new Error(`${svc.label} HTTP ${res.status}`);
  const body = await res.json();
  if (body.status && body.status !== 'OK') return [];
  const out = body.Resultados || [];

  // Windows that end before yesterday are final; recent ones may still be published or revised
  const ttl = b < addDays(todayMX(), -1) ? 7 * 86400 : 1800;
  if (cache) ctx.waitUntil(cache.put(key, new Response(JSON.stringify(out), { headers: { 'Content-Type': 'application/json', 'Cache-Control': `public, max-age=${ttl}` } })));
  return out;
}

/* ── SEN demand (Operación del SEN) ────────────── */
// gerencia: 10 = SIN, 1 = Baja California, 2 = Baja California Sur, 3–9 = SIN regions
const GERENCIAS = { 10: 'Sistema Interconectado Nacional', 1: 'Baja California', 2: 'Baja California Sur', 3: 'Central',
  4: 'Noreste', 5: 'Noroeste', 6: 'Norte', 7: 'Occidental', 8: 'Oriental', 9: 'Peninsular' };
const DEMANDA_URL = 'https://www.cenace.gob.mx/Paginas/SIM/OperacionSEN.aspx/obtieneValoresTotal';
const DEMANDA_TTL = 60;  // at most one CENACE call a minute per region, so the widget follows CENACE's page
const DEMANDA_FRESH = 15 * 1000;  // youngest cached answer the refresh button still accepts

async function demanda(p, ctx) {
  const g = String(p.get('gerencia') || '10');
  if (!Object.hasOwn(GERENCIAS, g)) throw fail(400, 'bad_request', 'gerencia must be 1 to 10.');
  const cache = typeof caches !== 'undefined' ? caches.default : null;
  const key = new Request(`https://sentinels-pml.cache/demanda/${g}`);
  // fresh=1 (the widget's refresh button) skips a cached answer older than DEMANDA_FRESH,
  // so CENACE still gets at most one call per region in that time however often it's clicked
  const fresh = p.get('fresh') === '1';
  if (cache) {
    const hit = await cache.match(key);
    if (hit) { const d = await hit.json(); if (!fresh || Date.now() - Date.parse(d.consultado) < DEMANDA_FRESH) return d; }
  }

  const res = await fetch(DEMANDA_URL, {
    method: 'POST', body: JSON.stringify({ gerencia: g }),
    headers: { 'Content-Type': 'application/json; charset=utf-8', Accept: 'application/json' }
  });
  if (!res.ok) throw new Error(`OperacionSEN HTTP ${res.status}`);
  // The page method answers { d: "<JSON text>" }; d is "" while CENACE has no data yet
  const d = (await res.json()).d;
  const rows = d ? JSON.parse(d) : [];
  const all = rows.map(r => ({ hora: Number(r.hora), demanda: num(r.valorDemanda), generacion: num(r.valorGeneracion), pronostico: num(r.valorPronostico) }))
    .filter(r => r.hora >= 1 && r.hora <= 25);
  // Rows come in time order; some regions start with hour 24 of the previous day, which
  // goes apart (previa) so it doesn't take the place of today's hour 24
  const first = all.findIndex(r => r.hora === 1);
  const previa = first > 0 ? all[first - 1] : null;
  const horas = all.slice(Math.max(0, first));
  // Now and then CENACE answers 0 MW for every hour; that is never real, so it isn't passed on
  // (the widget keeps showing its last answer and asks again)
  if (horas.some(h => h.demanda === 0)) throw new Error('OperacionSEN answered 0 MW');
  const out = { gerencia: Number(g), nombre: GERENCIAS[g], fecha: todayMX(), unidades: 'MW', fuente: 'CENACE · Operación del SEN', consultado: new Date(Date.now()).toISOString(), previa, horas };
  // CENACE switches between two sets of values for the hours already published during the
  // day (both show on its own page), so the answer is passed on as is and kept only briefly
  if (cache) ctx.waitUntil(cache.put(key, new Response(JSON.stringify(out), { headers: { 'Content-Type': 'application/json', 'Cache-Control': `public, max-age=${horas.length ? DEMANDA_TTL : 30}` } })));
  return out;
}

const num = v => v == null || String(v).trim() === '' || !isFinite(Number(v)) ? null : Number(v);
// One row shape for both services: pml = price; pml_ene / pml_per / pml_cng = energy / losses / congestion
const rowOf = svc => { const [p, e, l, c] = svc.fields; return v => ({ fecha: v.fecha, hora: Number(v.hora), pml: num(v[p]), pml_ene: num(v[e]), pml_per: num(v[l]), pml_cng: num(v[c]) }); };
